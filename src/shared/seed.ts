const esc = (s: string) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/** A generated card face (never real card art). The Slab component draws the holder around it. */
function cardFace(title: string, year?: number): string {
  const tcg = title.includes('Pokémon')
  const hue = [...title].reduce((h, c) => (h * 31 + c.charCodeAt(0)) % 360, 7)
  const frame = tcg ? '#f2c230' : `hsl(${hue} 55% 38%)`
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 250 350" width="250" height="350">
<rect width="250" height="350" rx="12" fill="${frame}"/>
<rect x="14" y="14" width="222" height="322" rx="6" fill="#fbfaf6"/>
<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="hsl(${hue} 70% 72%)"/><stop offset="1" stop-color="hsl(${(hue + 60) % 360} 60% 45%)"/></linearGradient></defs>
<rect x="24" y="24" width="202" height="220" rx="4" fill="url(#g)"/>
<circle cx="125" cy="134" r="58" fill="#fff" fill-opacity="0.28"/>
<path d="M92 214c6-40 60-40 66 0z M125 110a22 22 0 1 0 0.1 0z" fill="#fff" fill-opacity="0.55"/>
<rect x="24" y="256" width="202" height="48" rx="4" fill="${frame}"/>
<text x="125" y="286" font-family="Arial,sans-serif" font-size="15" font-weight="700" fill="#fff" text-anchor="middle">${esc(title)}</text>
<text x="125" y="324" font-family="Arial,sans-serif" font-size="12" fill="#5c5a52" text-anchor="middle">${year ?? ''}</text>
</svg>`
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`
}

type CardSeed = Omit<Listing, 'imageUrl' | 'category'> & { short: string }
const card = ({ short, ...l }: CardSeed): Listing => ({
  ...l,
  category: 'card',
  imageUrl: cardFace(short, l.year),
})

